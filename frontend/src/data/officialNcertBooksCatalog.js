export const formatChapterCode = (num) => {
  const n = Number(num) || 1;
  return n < 10 ? `0${n}` : `${n}`;
};

export const getNcertPdfUrl = (ncertCode, chapterNumber) => {
  const code = String(ncertCode || 'iemh1').toLowerCase().trim();
  const chFormatted = formatChapterCode(chapterNumber);
  return `https://ncert.nic.in/textbook/pdf/${code}${chFormatted}.pdf`;
};

